// ─── Translation registry ───────────────────────────────────────────────────

const translations: Record<LangCode, Translations> = {
  en, de, fr, es, it, pt, nl, pl, sv,
  da, fi, cs, sk, ro, hr, sl, bg, el, hu, et, lv, lt,
};

/** Translate a UI key for the given language, falling back to English. */
export function t(lang: string, key: TranslationKey): string {
  const code = lang as LangCode;
  const dict = translations[code];
  if (dict && dict[key]) return dict[key];
  return en[key] ?? key;
}

/** Detect UI language from localStorage or navigator.language. */
export function detectUILanguage(): LangCode {
  try {
    const stored = localStorage.getItem("ui_language");
    if (stored && (stored as LangCode) in translations) return stored as LangCode;
    const nav = navigator.language.split("-")[0].toLowerCase();
    if ((nav as LangCode) in translations) return nav as LangCode;
  } catch {
    // localStorage may be unavailable
  }
  return "en";
}

/** Persist chosen UI language. */
export function saveUILanguage(lang: LangCode): void {
  try {
    localStorage.setItem("ui_language", lang);
  } catch {
    // ignore
  }
}
